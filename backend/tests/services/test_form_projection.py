@pytest.mark.asyncio
async def test_fit_recovers_the_planted_time_constants():
    """Plant τ1 = 54 d, τ2 = 12 d in the data; the model must find them."""
    tss = _tss_history()
    obs = _perf_from(tss, 54.0, 12.0, k1=0.08, k2=0.12, p0=250.0, n_obs=20, noise=1.0)
    out = await _run(tss, _p20_days(tss, obs))

    assert out["available"] is True
    assert out["model"] == "individual", out["model_reason"]
    assert out["constants"]["tau1_days"] == pytest.approx(54.0, abs=4.0)
    assert out["constants"]["tau2_days"] == pytest.approx(12.0, abs=2.0)
    # And it is genuinely NOT the population default.
    assert out["constants"]["tau1_days"] != 42.0


@pytest.mark.asyncio
async def test_individual_model_diverges_from_the_standard_pmc():
    """The whole competitive claim: a different τ gives a different number, and
    the standard number ships alongside it so the difference is visible."""
    tss = _tss_history()
    obs = _perf_from(tss, 58.0, 14.0, k1=0.08, k2=0.12, p0=250.0, n_obs=20, noise=1.0)
    out = await _run(tss, _p20_days(tss, obs))

    assert out["model"] == "individual"
    assert out["standard_today"]["fitness"] != out["today"]["fitness"]
    # standard_today must still be the real PMC value for that day.
    rows = _pmc_rows(tss)
    assert out["standard_today"]["fitness"] == rows[-1]["ctl"]
    assert out["standard_today"]["form"] == rows[-1]["tsb"]


@pytest.mark.asyncio
async def test_submaximal_days_are_gated_out_of_the_fit():
    """A 20-min power off an easy ride is not a performance test."""
    tss = _tss_history()
    obs = _perf_from(tss, 54.0, 12.0, k1=0.08, k2=0.12, p0=250.0, n_obs=20, noise=1.0)
    out = await _run(tss, _p20_days(tss, obs, submaximal=15))

    ps = out["performance_series"]
    assert ps["n_candidate_days"] == ps["n_observations"] + 15   # all 15 easy days rejected
    assert ps["gate_watts"] == pytest.approx(ps["window_best_watts"] * 0.9, abs=0.06)
    assert all(p["watts"] >= ps["gate_watts"] for p in ps["points"])
    # The gate must not have eaten the real efforts along with the easy ones.
    assert out["model"] == "individual"


