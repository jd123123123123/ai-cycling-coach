"""Execution sayings — the deterministic backup behind the LLM's post-ride line.

The post-ride review already states the measured facts: target vs actual TSS,
duration, IF, and a grade. What it also needs is one human sentence about HOW
the ride went, and when the LLM is unavailable -- no API key, a timeout, a 503
-- that sentence still has to exist or the fallback reads like an invoice.

This is that sentence: one bank per grade, deep enough that a rider training
five times a week does not meet the same headline twice in a season.

── These are FLAVOUR, never claims ──────────────────────────────────────────
Every line comments on numbers the scorer has already computed and the card has
already printed. None of them state a fact of their own -- no line invents a
figure, a physiological effect, or a trend -- because the moment flavour text
starts asserting things it becomes another surface that can be wrong. The
compliance numbers are the truth; this is the tone. (`ride_compliance` remains
the sole authority on the grade itself; nothing here can change it.)

── Tone, per grade ──────────────────────────────────────────────────────────
`overcooked` and `undercooked` are the ones that matter, and neither is a
telling-off. Going too hard is usually enthusiasm and going too easy is usually
good judgement or a bad day -- both are normal, both get wry warmth rather than
correction. The next-session nudge (`_simple_nudge` / `_technical_nudge`) is
where actual advice lives; a headline's job is to be on the athlete's side.
"""
from __future__ import annotations

from datetime import date


def saying_for(bank: list[str], day: date, salt: str = "") -> str:
    """A line that is stable for a given day and cycles the WHOLE bank.

    Keyed on day-of-year rather than day-of-month: a month index against a
    100-line bank can only ever reach the first 31 entries, leaving 69 lines
    that would never once be shown. The grade is folded in as salt so an
    athlete whose rides land on different grades on consecutive days does not
    draw the same index from each bank.
    """
    if not bank:
        return ""
    h = 0
    for ch in salt:
        h = (h * 31 + ord(ch)) & 0xFFFFFFFF
    return bank[(day.timetuple().tm_yday + h) % len(bank)]


