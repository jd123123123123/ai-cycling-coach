def _tss_history(n_days: int = N_DAYS) -> list[float]:
    """A plausible block-periodised load: Monday off, Saturday long, 3-week ramp."""
    out = []
    for d in range(n_days):
        dow = d % 7
        if dow == 0:
            out.append(0.0)
        else:
            out.append(float(60 + 40 * ((d // 7) % 3) + (60 if dow == 5 else 0)))
    return out


def _perf_from(tss: list[float], tau1: float, tau2: float, k1: float, k2: float,
               p0: float, n_obs: int, noise: float = 0.0, seed: int = 7) -> dict[int, float]:
    """Performance generated BY the Banister model at a known (τ1, τ2)."""
    rnd = random.Random(seed)
    g1 = _convolve(tss, tau1)
    g2 = _convolve(tss, tau2)
    step = max(1, len(tss) // n_obs)
    obs: dict[int, float] = {}
    for i in range(n_obs):
        d = len(tss) - 1 - i * step
        if d < 0:
            break
        obs[d] = p0 + k1 * g1[d] - k2 * g2[d] + rnd.gauss(0, noise)
    return obs


def _pmc_rows(tss: list[float], today: date = TODAY) -> list[dict]:
    """A compute_user_pmc-shaped 'total' series with real CTL/ATL/TSB."""
    rows = []
    ctl = atl = 0.0
    start = today - timedelta(days=len(tss) - 1)
    for i, t in enumerate(tss):
        ctl, atl = update_ctl_atl(ctl, atl, t)
        e_ctl, e_atl = round(ctl, 1), round(atl, 1)
        rows.append({
            "date": start + timedelta(days=i),
            "ctl": e_ctl,
            "atl": e_atl,
            "tsb": round(e_ctl - e_atl, 1),
            "tss": t,
        })
    return rows


def _p20_days(tss: list[float], obs: dict[int, float], today: date = TODAY,
              submaximal: int = 0, band: tuple[float, float] = (272.0, 300.0)) -> dict[date, float]:
    """Turn model observations into a stored 20-min-power-by-day map.

    The model's raw output spans hundreds of "watts"; a real athlete's 20-min
    power moves ~10% across a season. So the observations are mapped AFFINELY
    into a realistic band — affine because p0/k1/k2 absorb the shift and scale
    exactly, leaving τ1/τ2 (the thing under test) untouched.

    This matters: with an unrealistic spread the 90% near-maximal gate censors
    the low half of the series and biases the fit. That is a real property of
    the gate, not a test artefact — see NEAR_MAXIMAL_FRACTION's docstring.

    `submaximal` extra days are added well under the gate (0.6 × best, roughly
    where an endurance ride's 20-min power sits) so the filter has something to
    reject.
    """
    start = today - timedelta(days=len(tss) - 1)
    lo, hi = min(obs.values()), max(obs.values())
    span = (hi - lo) or 1.0
    low_w, high_w = band
    out = {
        start + timedelta(days=i): low_w + (v - lo) * (high_w - low_w) / span
        for i, v in obs.items()
    }
    best = max(out.values())
    for j in range(submaximal):
        out.setdefault(start + timedelta(days=j * 3 + 1), best * 0.6)
    return out


def _mock_db() -> MagicMock:
    db = MagicMock()
    db.execute = AsyncMock()
    return db


async def _run(tss, p20_by_day, planned=None, horizon_days=14, today=TODAY):
    """Drive build_form_projection with every DB read stubbed."""
    planned = planned or {}
    rows = _pmc_rows(tss, today)

    async def _planned(db, user_id, start, end):
        return {d: v for d, v in planned.items() if start <= d <= end}

    with patch.object(fp, "compute_user_pmc", new=AsyncMock(return_value={"total": rows})), \
         patch.object(fp, "load_p20_by_day", new=AsyncMock(return_value=p20_by_day)), \
         patch.object(fp, "load_planned_tss", new=AsyncMock(side_effect=_planned)), \
         patch.object(fp, "today_local", return_value=today):
        return await build_form_projection(_mock_db(), 1, horizon_days=horizon_days)


# ─────────────────────────────────────────────────────────────────────────────
# Pure maths: the two convolutions must agree with what they claim to mirror
# ─────────────────────────────────────────────────────────────────────────────

def test_convolve_matches_impulse_response_components():
    """Our O(n) convolution IS impulse_response's O(n²) one — the fit is scored
    on the same numbers the fitter used."""
    tss = _tss_history(60)
    g1 = _convolve(tss, 42.0)
    g2 = _convolve(tss, 7.0)
    for day in (0, 1, 17, 41, 59):
        f, g = _components(tss, day, 42.0, 7.0)
        assert g1[day] == pytest.approx(f, rel=1e-9)
        assert g2[day] == pytest.approx(g, rel=1e-9)


def test_ewma_at_standard_tau_is_the_apps_own_ctl_atl():
    """The displayed fitness/fatigue must be the SAME recursion the PMC uses,
    or this screen and the PMC screen would disagree about the same day."""
    tss = _tss_history(120)
    fit = ewma_series(tss, 42.0)
    fat = ewma_series(tss, 7.0)
    ctl = atl = 0.0
    for i, t in enumerate(tss):
        ctl, atl = update_ctl_atl(ctl, atl, t)
        assert fit[i] == pytest.approx(ctl, rel=1e-12)
        assert fat[i] == pytest.approx(atl, rel=1e-12)


def test_aicc_undefined_below_seven_observations():
    """AICc for the 5-parameter model needs n > 6 — hence our stricter gate."""
    assert aicc(10.0, 6, 5) is None
    assert aicc(10.0, 8, 5) is not None
    assert MIN_OBSERVATIONS_FOR_INDIVIDUAL > 6


def test_forward_band_widens_with_horizon_and_form_band_is_not_the_naive_sum():
    """Fitness and fatigue ride the same uncertain load, so the form band must
    be tighter than adding their SDs in quadrature."""
    s1a, s2a, sfa = forward_band_sigma(3, 42.0, 7.0, 30.0)
    s1b, s2b, sfb = forward_band_sigma(21, 42.0, 7.0, 30.0)
    assert s1b > s1a and s2b > s2a
    naive = math.sqrt(s1b ** 2 + s2b ** 2)
    assert sfb < naive
    assert forward_band_sigma(0, 42.0, 7.0, 30.0) == (0.0, 0.0, 0.0)
    assert forward_band_sigma(10, 42.0, 7.0, 0.0) == (0.0, 0.0, 0.0)


def test_confidence_is_discounted_by_sample_count():
    """The same R² on 8 points must not claim the confidence it earns on 24."""
    assert confidence_pct_for(0.95, 8, 5) < confidence_pct_for(0.95, 24, 5)


