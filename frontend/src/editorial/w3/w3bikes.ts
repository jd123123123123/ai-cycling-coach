/**
 * W3 · The bike ladder — 26 bikes, from the rust bucket everyone starts on to
 * a WorldTour prototype.
 *
 * WHY A LADDER AND NOT AN UPLOAD. Digitalising the rider's own bike made the
 * bike a fixed possession: nothing to earn, nothing to spend RideCoin on, and a
 * paid image-model call on the critical path of onboarding. The ladder inverts
 * all three — the bike becomes the progression, RideCoin finally has a sink,
 * and the art is generated ONCE (see `scripts/generate-bikes.py`) and shipped
 * as static WebP. No per-rider render, no runtime dependency on an image model,
 * identical art for everyone, and a swap costs nothing.
 *
 * THE ART IS ALL ONE CAMERA. Every bike is rendered with the same locked
 * drive-side profile the studio uses (`cyclr_studio.BIKE_CAMERA`), so bikes are
 * comparable side by side in the garage, and the layered scene composer can pin
 * a rider and cosmetics to the same anchors regardless of which bike is
 * underneath.
 *
 * PRICES are in RideCoin and are the sink the economy was missing. `starter` is
 * owned by everyone from day one and cannot be bought or sold.
 */

export type BikeTier = 'starter' | 'steel' | 'alloy' | 'carbon' | 'pro'

export interface W3Bike {
  /** Stable id — the ownership key. Never renamed; the art file is named for it. */
  id: string
  name: string
  tier: BikeTier
  /** RideCoin price. 0 = the starter bike, granted to everyone. */
  price: number
  /** One line of character, shown on the shop tile and the garage detail. */
  blurb: string
  /** The literal description handed to the image model. Kept in the source so
   *  the art can be regenerated byte-identically (deterministic seed). */
  prompt: string
}

