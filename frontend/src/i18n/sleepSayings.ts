/**
 * English banks.
 *
 * ── A different grammar contract from the German ─────────────────────────
 * German renders `{base}{yesterday} — {saying}.`, so its fragments end the
 * sentence. English renders `{base} — {saying}{yesterday}.` — the saying sits
 * in the MIDDLE and a clause is appended after it:
 *
 *   Slept 7.4h (88) — recovery banked in full after yesterday's 62 TSS.
 *
 * So these have to be noun phrases (or short clauses) that still read when
 * " after yesterday's rest day" is glued to the end. Anything that already
 * ends in a preposition, or that reads as a complete sentence, breaks there.
 * That is why these are not translations of the German lines: the German bank
 * can close a thought, this one cannot.
 */

