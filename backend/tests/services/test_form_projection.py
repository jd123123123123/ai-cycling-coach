@pytest.mark.asyncio
async def test_projection_with_no_plan_is_labelled_an_assumption():
    """A projection nobody planned must not be presented as a plan."""
    tss = _tss_history()
    out = await _run(tss, {}, planned={}, horizon_days=14)

    assert out["load"]["source"] == "recent-average"
    assert out["load"]["planned_days"] == 0
    assert out["load"]["assumption"] is not None
    assert "not a prescription" in out["load"]["assumption"]
    assert str(out["load"]["rolling_7d_tss"]) in out["load"]["assumption"]
    assert all(d["load_source"] == "recent-average" for d in out["projection"])
    # And the assumed load really is the 7-day rolling average, not a guess.
    assert all(d["tss"] == out["load"]["rolling_7d_tss"] for d in out["projection"])


@pytest.mark.asyncio
async def test_planned_days_are_labelled_plan_and_rest_days_are_zero():
    tss = _tss_history()
    planned = {TODAY + timedelta(days=i): 90.0 for i in range(1, 11) if i % 3}
    out = await _run(tss, {}, planned=planned, horizon_days=14)

    assert out["load"]["source"] == "mixed"
    assert out["load"]["planned_days"] == 10          # the covered span, incl. rest days
    assert out["load"]["assumption"] is not None      # days 11-14 are still assumed
    by_offset = {d["days_out"]: d for d in out["projection"]}
    assert by_offset[1]["load_source"] == "plan" and by_offset[1]["tss"] == 90.0
    # Inside the plan's span, a day with no session is a REST day, not a gap.
    assert by_offset[3]["load_source"] == "plan" and by_offset[3]["tss"] == 0.0
    assert by_offset[12]["load_source"] == "recent-average"


