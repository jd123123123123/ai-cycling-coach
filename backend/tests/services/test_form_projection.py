"""Individualized fitness/fatigue/form — the fit, and the honesty gates.

The point of this feature is not that it fits a curve; it is that it refuses to
call a curve "individual" when it isn't. These tests pin the refusals as hard
as they pin the fit:

  · the fit recovers a τ we planted (so "individual" means something)
  · below the observation threshold → standard constants, and it SAYS so
  · when the truth IS 42/7 the AICc rejects the individual fit even though its
    in-sample R² is higher (the in-sample trap)
  · a projection with no plan behind it is labelled an assumption
  · at τ=42/7 the numbers are bit-identical to the app's PMC recursion
"""
