/**
 * Sleep sayings — the deterministic backup behind the LLM's morning read.
 *
 * The morning read names a real number ("7,4 h Schlaf (Score 88)") and then
 * says something human about it. When the LLM is unavailable — no API key, a
 * timeout, a 503 — that human half still has to exist, or the fallback reads
 * like a receipt. This is that half: one bank per sleep state, deep enough that
 * a daily rider does not meet the same line twice in a season.
 *
 * ── These are FLAVOUR, never claims ──────────────────────────────────────
 * Every line here is a comment on a number the app has already measured and
 * printed. None of them state a fact of their own — no line invents a reason,
 * a trend, or a physiological claim, because the moment flavour text starts
 * asserting things it becomes another surface that can be wrong. The number is
 * the truth; this is the tone.
 *
 * ── Grammar contract ─────────────────────────────────────────────────────
 * Fragments, lowercase, no trailing punctuation. They are appended after an
 * em dash: `7,4 h Schlaf (Score 88) nach 62 TSS gestern — {saying}.`
 * Anything that would not survive that sentence does not belong in the bank.
 *
 * ── Tone ─────────────────────────────────────────────────────────────────
 * `short` is the one that matters. A bad night is not a moral failure and the
 * athlete already knows it was bad — so the bank is wry and calm, never
 * alarmed and never scolding. It follows the register the morning health card
 * settled on: state it plainly, keep it light, do not catastrophise. Nothing
 * in `short` tells the rider to train or not to train; that is the readiness
 * gate's job, not a joke's.
 */

export type SleepState = 'great' | 'ok' | 'short'

/**
 * Pick a saying that is stable for a given day and cycles through the WHOLE
 * bank across the year.
 *
 * The previous picker was `arr[date.getDate() % arr.length]` — day of month.
 * Against a 3-variant array that was fine; against a 100-line bank it can only
 * ever reach the first 31, leaving 69 lines that would never once be shown.
 * Day-of-year fixes the range, and the state name is folded in so a rider whose
 * sleep flips between two states on consecutive days does not get the same
 * index in both banks.
 */
export function sayingFor(bank: readonly string[], date: Date, salt = ''): string {
  if (bank.length === 0) return ''
  const start = new Date(date.getFullYear(), 0, 0)
  const dayOfYear = Math.floor((date.getTime() - start.getTime()) / 86_400_000)
  let h = 0
  for (let i = 0; i < salt.length; i++) h = (h * 31 + salt.charCodeAt(i)) | 0
  return bank[Math.abs(dayOfYear + h) % bank.length]
}

