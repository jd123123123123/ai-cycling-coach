@pytest.mark.asyncio
async def test_below_the_observation_threshold_falls_back_and_says_so():
    tss = _tss_history()
    obs = _perf_from(tss, 54.0, 12.0, k1=0.08, k2=0.12, p0=250.0, n_obs=5)
    out = await _run(tss, _p20_days(tss, obs))

    assert out["model"] == "standard"
    assert out["fallback_reason"] == "too_few_performance_observations"
    assert out["constants"]["tau1_days"] == 42.0
    assert out["constants"]["tau2_days"] == 7.0
    # No fitted constants may be presented on the fallback path.
    assert out["constants"]["k1"] is None
    assert out["constants"]["r_squared"] is None
    # The standard model is never claimed as an individual measurement.
    assert out["confidence_pct"] == STANDARD_MODEL_CONFIDENCE_PCT
    assert out["range_required"] is True
    assert "not yet have enough" in out["model_reason"]
    # Falling back means agreeing exactly with the PMC.
    assert out["today"]["fitness"] == out["standard_today"]["fitness"]
    assert out["today"]["form"] == out["standard_today"]["form"]


