@pytest.mark.asyncio
async def test_when_the_truth_is_42_7_the_individual_fit_is_rejected():
    """The in-sample trap. The τ grid CONTAINS 42/7, so the fitted model's R²
    is always ≥ the standard model's — here it wins on R² and still loses on
    AICc, because its two extra parameters bought nothing. It must be rejected."""
    tss = _tss_history()
    obs = _perf_from(tss, 42.0, 7.0, k1=0.08, k2=0.12, p0=250.0, n_obs=20, noise=1.0)
    out = await _run(tss, _p20_days(tss, obs))

    assert out["model"] == "standard"
    assert out["fallback_reason"] == "standard_constants_fit_better"
    assert out["constants"]["tau1_days"] == 42.0
    assert out["constants"]["standard_aicc"] < out["constants"]["aicc"]
    assert "did not beat them" in out["model_reason"]


def test_raw_r_squared_alone_would_have_shipped_the_worse_model():
    """Guard on the reasoning, not just the outcome: prove that comparing R²
    (instead of AICc) really would pick 'individual' on 42/7 data."""
    from app.services.impulse_response import fit_fitness_fatigue

    tss = _tss_history()
    obs = _perf_from(tss, 42.0, 7.0, k1=0.08, k2=0.12, p0=250.0, n_obs=20, noise=1.0)
    fitted = fit_fitness_fatigue(tss, obs, min_points=8)
    std_rss, std_r2 = score_at_fixed_tau(tss, obs, 42.0, 7.0)
    ind_rss, ind_r2 = score_at_fixed_tau(tss, obs, fitted.tau1, fitted.tau2)

    assert ind_r2 >= std_r2                     # R² can never prefer standard…
    assert aicc(ind_rss, len(obs), 5) > aicc(std_rss, len(obs), 3)   # …AICc can.


