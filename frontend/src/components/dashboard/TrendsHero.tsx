import { usePMC } from '../../hooks/usePMC'
import { useDailyMetrics } from '../../hooks/useDailyMetrics'
import { subDays } from 'date-fns'
import type { PMCEntry } from '../../api/dashboard'
import Sparkline from './Sparkline'
import { useLocale } from '../../contexts/LocaleContext'
import { useLanguage } from '../../contexts/LanguageContext'
import { metricLabel } from '../../utils/metricLabel'
import { useGlossary } from '../ui/GlossarySheet'

type Loc = 'en' | 'de'

/**
 * TrendsHero — the first card on the Trends tab. A 90-day summary that
 * answers "where am I, and which way am I trending" before the full
 * instrument panel below.
 *
 * AI-driven narrative: each PMCEntry from the backend carries a per-day
 * `narrative` field (plain-English summary). The latest non-null narrative
 * sits next to the numbers — already AI prose, never previously surfaced
 * outside the PMCChart hover tooltip.
 */

function signed(n: number, digits = 0): string {
  return (n >= 0 ? '+' : '') + (digits === 0 ? Math.round(n) : n.toFixed(digits))
}

function formStatus(tsb: number | null, locale: Loc): { label: string; color: string } {
  if (tsb == null) return { label: locale === 'de' ? 'Unbekannt' : 'Unknown', color: 'var(--color-muted)' }
  if (tsb > 15) return { label: locale === 'de' ? 'Frisch' : 'Fresh', color: 'var(--color-good)' }
  if (tsb > 5) return { label: locale === 'de' ? 'Wettkampfbereit' : 'Race-ready', color: 'var(--color-good)' }
  if (tsb >= -10) return { label: locale === 'de' ? 'Optimal' : 'Optimal', color: 'var(--color-ink)' }
  if (tsb >= -22) return { label: locale === 'de' ? 'Produktiv' : 'Productive', color: 'var(--color-caution)' }
  return { label: locale === 'de' ? 'Tiefe Ermüdung' : 'Deep fatigue', color: 'var(--color-bad)' }
}

function ctlTrendNarrative(series: PMCEntry[], locale: Loc): string | null {
  if (series.length < 8) return null
  const latest = series[series.length - 1]
  const week = series[series.length - 8]
  const month = series.length >= 29 ? series[series.length - 29] : series[0]
  const dCtl7 = latest.ctl - week.ctl
  const dCtl28 = latest.ctl - month.ctl
  if (locale === 'de') {
    const verb = dCtl7 >= 1.5 ? 'steigt schnell' : dCtl7 >= 0.4 ? 'steigt stetig' : dCtl7 >= -0.4 ? 'bleibt stabil' : 'baut ab'
    const monthLabel = dCtl28 >= 3 ? `hoch ${signed(dCtl28)} über 28T` : dCtl28 <= -3 ? `runter ${signed(dCtl28)} über 28T` : 'stabil über 28T'
    return `Fitness ${verb} (${signed(dCtl7)} in 7T, ${monthLabel}).`
  }
  const verb = dCtl7 >= 1.5 ? 'climbing fast' : dCtl7 >= 0.4 ? 'climbing steadily' : dCtl7 >= -0.4 ? 'holding flat' : 'detraining'
  const monthDir = dCtl28 >= 3 ? 'up' : dCtl28 <= -3 ? 'down' : 'flat'
  const monthLabel = monthDir === 'flat' ? 'flat over 28d' : `${monthDir} ${signed(dCtl28)} over 28d`
  return `Fitness ${verb} (${signed(dCtl7)} in 7d, ${monthLabel}).`
}

export default function TrendsHero() {
  const { locale } = useLocale()
  const { language } = useLanguage()
  const glossary = useGlossary()
  const today = useMemo(() => new Date(), [])
  const { data: pmc, isLoading } = usePMC(90)
  const { data: metricsResp } = useDailyMetrics(useMemo(() => subDays(today, 28), [today]), today)

  if (isLoading) {
    return <div className="rounded-[18px] h-32 animate-pulse" style={{ backgroundColor: 'var(--color-rule)' }} />
  }

  const series = pmc?.entries ?? []
  if (series.length === 0) return null

  const latest = series[series.length - 1]
  const ctl = latest.ctl
  const atl = latest.atl
  const tsb = latest.tsb
  const form = formStatus(tsb, locale)

  // 7-day deltas
  const priorWeek = series.length >= 8 ? series[series.length - 8] : series[0]
  const dCtl = ctl - priorWeek.ctl
  const dAtl = atl - priorWeek.atl

  // Sparkline series
  const ctlSeries = series.map((e) => e.ctl)

  // AI-driven micro-narrative line. Prefer the latest non-null per-day
  // narrative from the PMC entries (already AI-generated by the backend
  // narrative service); fall back to a composed trend line when absent.
  const aiPerDay = [...series]
    .reverse()
    .find((e) => typeof e.narrative === 'string' && e.narrative!.trim().length > 0)?.narrative
  const composedTrend = ctlTrendNarrative(series, locale)
  const narrative = (aiPerDay && aiPerDay.trim()) || composedTrend

  // Volume summary — 28-day TSS total + HRV/RHR coverage
  const last28 = series.slice(-28)
  const tss28 = Math.round(last28.reduce((s, e) => s + (e.daily_tss ?? 0), 0))
  const hrvDaysAvail = (metricsResp?.metrics ?? []).filter((m) => m.hrv_status != null).length

  return (
    <div
      className="rounded-[18px] p-5 sm:p-6"
      style={{
        backgroundColor: 'var(--color-paper-2)',
        border: '1px solid var(--color-rule)',
      }}
    >
      {/* Eyebrow */}
      <div className="flex items-center gap-3 flex-wrap mb-3">
        <span className="eyebrow num-mono" style={{ color: 'var(--color-ink-2)', fontSize: 10, letterSpacing: '0.22em' }}>
          {locale === 'de' ? 'TRENDS · 90 TAGE' : 'TRENDS · 90 DAYS'}
        </span>
        <span style={{ color: 'var(--color-muted)', fontSize: 10 }}>·</span>
        <span className="eyebrow num-mono" style={{ color: form.color, fontSize: 10, letterSpacing: '0.22em' }}>
          {form.label.toUpperCase()}
        </span>
      </div>

      {/* AI narrative */}
      {narrative && (
        <p
          className="text-[14px] sm:text-[15px] leading-relaxed mb-4"
          style={{ color: 'var(--color-ink)', maxWidth: '64ch' }}
        >
          {narrative}
        </p>
      )}

      {/* Triple stat row + CTL sparkline. Simple mode routes labels through
          metricLabel (P1: 'Einfach' governs the UI); technical stays verbatim.
          Every stat is a tappable chip → glossary bottom sheet. */}
      <div className="grid grid-cols-1 sm:grid-cols-[1fr_1fr_1fr_auto] gap-x-6 gap-y-3 items-center">
        <Stat
          label={language === 'simple' ? metricLabel('ctl', 'simple', locale).toUpperCase() : 'FITNESS · CTL'}
          value={String(Math.round(ctl))}
          sub={`${signed(dCtl)} · 7${locale === 'de' ? 'T' : 'd'}`}
          subColor={dCtl >= 0.4 ? 'var(--color-good)' : dCtl <= -0.4 ? 'var(--color-bad)' : 'var(--color-muted)'}
          onTap={() => glossary.open('ctl', String(Math.round(ctl)))}
        />
        <Stat
          label={language === 'simple' ? metricLabel('atl', 'simple', locale).toUpperCase() : locale === 'de' ? 'ERMÜDUNG · ATL' : 'FATIGUE · ATL'}
          value={String(Math.round(atl))}
          sub={`${signed(dAtl)} · 7${locale === 'de' ? 'T' : 'd'}`}
          subColor={dAtl >= 2 ? 'var(--color-caution)' : 'var(--color-muted)'}
          onTap={() => glossary.open('atl', String(Math.round(atl)))}
        />
        <Stat
          label={language === 'simple' ? metricLabel('tsb', 'simple', locale).toUpperCase() : 'FORM · TSB'}
          value={signed(tsb)}
          valueColor={form.color}
          onTap={() => glossary.open('tsb', signed(tsb))}
        />
        <div className="hidden sm:block">
          <span className="eyebrow" style={{ color: 'var(--color-muted)', fontSize: 10.5, letterSpacing: '0.22em' }}>
            {locale === 'de' ? 'FITNESS · 90T' : 'FITNESS · 90D'}
          </span>
          <div className="mt-1">
            <Sparkline values={ctlSeries} width={180} height={36} stroke="var(--color-ink-2)" showDot={false} />
          </div>
        </div>
      </div>

      {/* Footer row — 28-day load + HRV coverage */}
      <div
        className="flex items-center gap-4 flex-wrap mt-4 pt-3"
        style={{ borderTop: '1px solid var(--color-rule)' }}
      >
        <button
          type="button"
          className="num-mono"
          onClick={() => glossary.open('tss', String(tss28))}
          style={{
            color: 'var(--color-muted)', fontSize: 11, background: 'none', border: 0,
            padding: '14px 0', margin: '-14px 0', cursor: 'pointer',
            textDecoration: 'underline dotted', textUnderlineOffset: 3, textDecorationColor: 'var(--color-muted)',
          }}
        >
          {language === 'simple'
            ? (locale === 'de' ? '28-Tage-Belastung' : '28-day Load')
            : (locale === 'de' ? '28-Tage-TSS' : '28-day TSS')} · <span style={{ color: 'var(--color-ink)' }}>{tss28}</span>
        </button>
        <span className="num-mono" style={{ color: 'var(--color-muted)', fontSize: 11 }}>
          {locale === 'de' ? 'HRV-Tage' : 'HRV days'} · <span style={{ color: 'var(--color-ink)' }}>{hrvDaysAvail}/28</span>
        </span>
      </div>
      {glossary.sheet}
    </div>
  )
}

function Stat({
  label,
  value,
  sub,
  valueColor = 'var(--color-ink)',
  subColor = 'var(--color-muted)',
  onTap,
}: {
  label: string
  value: string
  sub?: string
  valueColor?: string
  subColor?: string
  /** When set, the whole stat becomes a ≥44px tap target → glossary sheet. */
  onTap?: () => void
}) {
  const inner = (
    <>
      <span
        className="eyebrow"
        style={{
          color: 'var(--color-muted)', fontSize: 10.5, letterSpacing: '0.22em',
          ...(onTap
            ? { textDecoration: 'underline dotted', textUnderlineOffset: 3, textDecorationColor: 'var(--color-muted)' }
            : null),
        }}
      >
        {label}
      </span>
      <span className="num-mono leading-none mt-0.5" style={{ color: valueColor, fontSize: 28, fontWeight: 500 }}>
        {value}
      </span>
      {sub && (
        <span className="num-mono mt-1" style={{ color: subColor, fontSize: 11 }}>
          {sub}
        </span>
      )}
    </>
  )
  if (onTap) {
    return (
      <button
        type="button"
        onClick={onTap}
        className="flex flex-col items-start"
        style={{ background: 'none', border: 0, padding: 0, minHeight: 44, cursor: 'pointer', textAlign: 'left' }}
      >
        {inner}
      </button>
    )
  }
  return <div className="flex flex-col">{inner}</div>
}
