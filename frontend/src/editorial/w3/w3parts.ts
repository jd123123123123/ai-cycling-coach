/**
 * W3 · Parts — the cosmetics a rider buys to make a bike theirs.
 *
 * Four slots: RAHMEN (paint/decals), REIFEN (wheels + tyres), LENKER (bars and
 * tape), SATTEL. Bought with RideCoin, the same sink the bike ladder uses.
 *
 * WHY PARTS ARE LAYERS AND NOT RE-RENDERS. A cosmetic swap must be instant and
 * free — a rider trying five bar tapes cannot mean five paid image-model calls,
 * and the bike must not shift by a pixel between them. So each part is a
 * SEPARATE image pinned to shared anchors, exactly as the deleted `w3scene.ts`
 * composer described: swapping a helmet replaces one layer's src and nothing
 * else moves. That property is the whole reason the layered model beats the
 * generate-the-whole-scene approach for cosmetics.
 *
 * CAMERA. Each slot has its OWN locked camera (see `SLOT_CAMERA`), because a
 * wheel and a saddle are not legible from the same angle. Within a slot every
 * part is shot identically, so parts are comparable in the shop and
 * interchangeable in the composite.
 *
 * The art is generated once by `backend/scripts/generate_parts.py` and shipped
 * static, same as the bikes.
 */

export type PartSlot = 'frame' | 'wheels' | 'bars' | 'saddle'

export interface W3Part {
  /** Stable id — the ownership key and the art filename. */
  id: string
  name: string
  slot: PartSlot
  /** RideCoin price. 0 = the stock part every bike already wears. */
  price: number
  blurb: string
  /** The literal description handed to the image model. Kept beside the part so
   *  the art can be regenerated byte-identically (seed derives from the id). */
  prompt: string
}

